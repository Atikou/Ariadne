import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const componentsRoot = path.join(
  projectRoot,
  'runtime', 'src', 'composition', 'agent-entity', 'components'
);
const outputPath = path.join(
  projectRoot,
  'runtime', 'src', 'composition', 'agent-entity',
  'AgentCoreComponentCatalog.generated.ts'
);
const checkOnly = process.argv.includes('--check');

const directories = readdirSync(componentsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort(compareCodeUnits);
const invalid = directories.filter((name) => !/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/u.test(name));
if (invalid.length > 0) {
  throw new Error(`agent_component_directory_invalid:${invalid.join(',')}`);
}
const missing = directories.filter((name) => !existsSync(path.join(
  componentsRoot, name, 'component.ts'
)));
if (missing.length > 0) {
  throw new Error(`agent_component_descriptor_missing:${missing.join(',')}`);
}
const expected = render(directories);
if (checkOnly) {
  const actual = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (actual !== expected) {
    process.stderr.write(
      'Agent component catalog is stale. Run npm run generate:agent-components.\n'
    );
    process.exit(1);
  }
  process.stdout.write(`Agent component catalog check passed: ${directories.length} components.\n`);
} else {
  writeFileSync(outputPath, expected, 'utf8');
  process.stdout.write(`Generated Agent component catalog: ${directories.length} components.\n`);
}

function render(names) {
  const imports = names.map((name, index) => (
    `import component${String(index)} from './components/${name}/component.js';`
  ));
  const entries = names.map((_name, index) => `  component${String(index)}`);
  return [
    '/* This file is generated by scripts/generate-agent-component-catalog.mjs. */',
    "import type { ComponentDefinition } from '@ariadne/component-contracts';",
    '',
    ...imports,
    '',
    'const DEFINITIONS = Object.freeze([',
    `${entries.join(',\n')}`,
    ']);',
    '',
    'export function agentCoreComponentDefinitions(): readonly ComponentDefinition[] {',
    '  return DEFINITIONS;',
    '}',
    ''
  ].join('\n');
}

function compareCodeUnits(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}
