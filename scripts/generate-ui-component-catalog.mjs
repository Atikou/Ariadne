import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const modulesRoot = path.join(
  projectRoot, 'app', 'src', 'renderer', 'src', 'modules'
);
const outputPath = path.join(
  projectRoot, 'app', 'src', 'renderer', 'src', 'core', 'modules',
  'UiComponentCatalog.generated.ts'
);
const checkOnly = process.argv.includes('--check');

const directories = readdirSync(modulesRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort(compareCodeUnits);
const invalid = directories.filter((name) => !/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/u.test(name));
if (invalid.length > 0) {
  throw new Error(`ui_component_directory_invalid:${invalid.join(',')}`);
}
const missing = directories.filter((name) => !existsSync(path.join(modulesRoot, name, 'index.ts')));
if (missing.length > 0) {
  throw new Error(`ui_component_descriptor_missing:${missing.join(',')}`);
}
const modules = directories.map((directory) => ({
  directory,
  exportName: readExportName(directory)
}));
const expected = render(modules);
if (checkOnly) {
  const actual = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (actual !== expected) {
    process.stderr.write(
      'UI component catalog is stale. Run npm run generate:ui-components.\n'
    );
    process.exit(1);
  }
  process.stdout.write(`UI component catalog check passed: ${modules.length} components.\n`);
} else {
  writeFileSync(outputPath, expected, 'utf8');
  process.stdout.write(`Generated UI component catalog: ${modules.length} components.\n`);
}

function readExportName(directory) {
  const source = readFileSync(path.join(modulesRoot, directory, 'index.ts'), 'utf8');
  const matches = [...source.matchAll(/export const ([A-Za-z][A-Za-z0-9]*)Module\s*:/gu)];
  if (matches.length !== 1 || matches[0]?.[1] === undefined) {
    throw new Error(`ui_component_export_invalid:${directory}`);
  }
  return `${matches[0][1]}Module`;
}

function render(modules) {
  const imports = modules.map(({ directory, exportName }) => (
    `import { ${exportName} } from '@renderer/modules/${directory}';`
  ));
  return [
    '/* This file is generated by scripts/generate-ui-component-catalog.mjs. */',
    "import type { FeatureModuleDefinition } from './module-contract';",
    '',
    ...imports,
    '',
    'const DEFINITIONS = Object.freeze([',
    ...modules.map(({ exportName }) => `  ${exportName},`),
    ']);',
    '',
    'export function uiComponentDefinitions(): readonly FeatureModuleDefinition[] {',
    '  return DEFINITIONS;',
    '}',
    ''
  ].join('\n');
}

function compareCodeUnits(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}
