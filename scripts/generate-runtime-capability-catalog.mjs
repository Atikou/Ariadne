import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const componentsRoot = path.join(
  projectRoot, 'runtime', 'src', 'composition', 'runtime-capabilities', 'components'
);
const outputPath = path.join(
  projectRoot, 'runtime', 'src', 'composition', 'runtime-capabilities',
  'ProductionRuntimeCapabilityCatalog.generated.ts'
);
const checkOnly = process.argv.includes('--check');
const directories = readdirSync(componentsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort(compare);
const invalid = directories.filter((name) => !/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/u.test(name));
if (invalid.length > 0) throw new Error(`runtime_capability_directory_invalid:${invalid.join(',')}`);
const missing = directories.filter((name) => !existsSync(path.join(componentsRoot, name, 'component.ts')));
if (missing.length > 0) throw new Error(`runtime_capability_descriptor_missing:${missing.join(',')}`);
const expected = render(directories);
if (checkOnly) {
  const actual = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (actual !== expected) {
    process.stderr.write('Runtime capability catalog is stale. Run npm run generate:runtime-capabilities.\n');
    process.exit(1);
  }
  process.stdout.write(`Runtime capability catalog check passed: ${directories.length} components.\n`);
} else {
  writeFileSync(outputPath, expected, 'utf8');
  process.stdout.write(`Generated Runtime capability catalog: ${directories.length} components.\n`);
}

function render(names) {
  return [
    '/* This file is generated by scripts/generate-runtime-capability-catalog.mjs. */',
    "import type { RuntimeCapabilityProvider } from './RuntimeCapabilityProvider.js';",
    '',
    ...names.map((name, index) => `import component${index} from './components/${name}/component.js';`),
    '',
    'const COMPONENTS = Object.freeze([',
    ...names.map((_name, index) => `  component${index},`),
    ']);',
    '',
    'export function productionRuntimeCapabilityProviders(): readonly RuntimeCapabilityProvider[] {',
    '  return Object.freeze(COMPONENTS.flatMap((providers) => providers));',
    '}',
    ''
  ].join('\n');
}

function compare(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}
